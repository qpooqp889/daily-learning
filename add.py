def guess_idiom_cat(idiom, explanation):
    if idiom in IDIOM_CAT_MAP:
        return IDIOM_CAT_MAP[idiom]
    text = (idiom or "") + (explanation or "")
    for cat, kws in IDIOM_CAT_KEYWORDS.items():
        if any(k in text for k in kws):
            return cat
    return "情境"

