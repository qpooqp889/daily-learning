DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
WORDS_FILE = os.path.join(DATA_DIR, "words.json")
IDIOMS_FILE = os.path.join(DATA_DIR, "idioms.json")

def load(path):
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def save(path, data):
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def norm(s):
    """正規化：去除空白、全形轉半形、統一大小寫，用於比對"""
    s = unicodedata.normalize("NFC", (s or "").strip())
    s = s.replace(" ", "").replace("\u3000", "")
    return s.casefold()

# ---------- 重複檢查 ----------
def find_duplicates():
    words = load(WORDS_FILE)
    idioms = load(IDIOMS_FILE)
    dup_words, dup_idioms = [], []
    seen_w, seen_i = {}, {}
    for w in words:
        key = norm(w["word"])
        if key in seen_w:
            dup_words.append(w["word"])
        else:
            seen_w[key] = w["word"]
    for i in idioms:
        key = norm(i["idiom"])
        if key in seen_i:
            dup_idioms.append(i["idiom"])
        else:
            seen_i[key] = i["idiom"]
    return dup_words, dup_idioms

def word_exists(word):
    return any(norm(w["word"]) == norm(word) for w in load(WORDS_FILE))

def idiom_exists(idiom):
    return any(norm(i["idiom"]) == norm(idiom) for i in load(IDIOMS_FILE))

def next_id(items):
    # 只取整數 id（部分舊資料的 id 是字串格式，需忽略避免型別錯誤）
    ids = [it.get("id", 0) for it in items if isinstance(it.get("id"), int)]
    return max(ids, default=0) + 1

